// Package orm maps Go structs to database tables using reflection.
//
// A model is a struct. Its exported fields map to columns named in
// snake_case, and the table name is the snake_case plural of the type name
// (User -> users, BlogPost -> blog_posts). The `orm` struct tag changes the
// mapping. It holds properties separated by semicolons:
//
//	column=name       column name
//	table=name        table of the model; may be set on any field,
//	                  typically on an embedded base struct
//	database=name     connection name from config (default "default")
//	primary           part of the primary key
//	auto_increment    generated by the database on insert
//	skip              not read or written unless named explicitly
//	base64            []byte stored as base64 text
//	foreign_key=a,b   key columns of a relation
//	order=col [desc]  sort order of a has-many relation
//	limit=n           row limit of a has-many relation
//	filter=Method     method of the model returning an extra condition for
//	                  a has-many relation
//	-                 ignore the field
//
// A field whose type is a struct (or pointer to one) other than time.Time
// is a belongs-to relation, and a slice of structs is a has-many relation.
// By default, the foreign key column is the singular name of the
// referenced table plus "_" plus its primary key column (user_id):
//
//	type Model struct {
//		Id int64 `orm:"primary; auto_increment"`
//	}
//
//	type Post struct {
//		Model    `orm:"table=blog_posts"`
//		UserId   int64
//		Title    string
//		User     *User                          // belongs to users via user_id
//		Comments []*Comment `orm:"order=id desc"` // has many via post_id
//	}
//
// Queries are built with the package-level functions, which each start a
// new Query:
//
//	var posts []*Post
//	err := orm.Where(query.Eq{"user_id": 1}).With("User", "Comments").Find(&posts)
//
// Loaded models can be cached in a cache storage, which is disabled by
// default. See SetCacheStorage.
package orm

import (
	"encoding/base64"
	"encoding/json"
	"fmt"
	"reflect"
	"regexp"
	"strings"

	"github.com/olegshs/go-tools/cache"
	"github.com/olegshs/go-tools/database"
	"github.com/olegshs/go-tools/database/interfaces"
	"github.com/olegshs/go-tools/database/query"
	"github.com/olegshs/go-tools/helpers"
	"github.com/olegshs/go-tools/helpers/typeconv"
)

var (
	// relationNameRegexp parses relation names for With, such as
	// "Posts[User, Comments]", where the bracketed names are loaded on the
	// related models.
	relationNameRegexp = regexp.MustCompile(`^(\w+)(\s*\[\s*(.*)\s*])?$`)
)

// Query is an ORM query. It holds the state of a single operation, so use a
// new Query for each one, as the package-level functions do. A Query is
// not safe for concurrent use.
type Query struct {
	tx         interfaces.DB
	columns    helpers.Slice[string]
	relations  []queryRelation
	conditions []interface{}
	order      []interface{}
	limit      []int

	model      interface{}
	modelValue reflect.Value
	modelInfo  *ModelInfo

	// belongsToCache remembers belongs-to models loaded during this query,
	// by field name and key, so Find does not load the same parent for every
	// row.
	belongsToCache map[string]map[string]reflect.Value
}

// queryRelation is a relation to load and the relations to load on its
// models in turn.
type queryRelation struct {
	name string
	with []string
}

// fieldsData holds the fields, columns and scan destinations of the
// columns being read.
type fieldsData struct {
	fields  []reflect.Value
	columns []interface{}
	values  []interface{}
	info    []*FieldInfo
}

// Tx runs the query on tx, such as a *database.Tx, instead of the model's
// connection. Related models are still loaded outside of tx.
func (q *Query) Tx(tx interfaces.DB) *Query {
	q.tx = tx
	return q
}

// Select limits reading to the given columns. Models read with selected
// columns are not cached.
func (q *Query) Select(columns ...string) *Query {
	q.columns = columns
	return q
}

// With loads the named relation fields along with the models. A name may be
// followed by relations of the related model in brackets, such as
// "Posts[Comments]". It panics if a name cannot be parsed.
func (q *Query) With(relations ...string) *Query {
	a := make([]queryRelation, len(relations))
	for i, r := range relations {
		a[i] = q.parseRelationName(r)
	}

	q.relations = append(q.relations, a...)
	return q
}

// Where adds conditions, in any form accepted by package query.
func (q *Query) Where(conditions ...interface{}) *Query {
	q.conditions = append(q.conditions, conditions...)
	return q
}

// Order adds ORDER BY items, in any form accepted by package query.
func (q *Query) Order(order ...interface{}) *Query {
	q.order = append(q.order, order...)
	return q
}

// Limit sets the row limit: Limit(n) or Limit(offset, n).
func (q *Query) Limit(limit ...int) *Query {
	q.limit = limit
	return q
}

// Count returns the number of rows that match the conditions in the table
// of model. model may be a struct, a pointer or a slice of the model type.
func (q *Query) Count(model interface{}) (int, error) {
	t := reflect.TypeOf(model)
	for (t.Kind() == reflect.Ptr) || (t.Kind() == reflect.Slice) {
		t = t.Elem()
	}

	err := q.setModelByType(t)
	if err != nil {
		return 0, err
	}

	db, err := q.modelDB()
	if err != nil {
		return 0, err
	}

	row := db.Select(query.Expr(`COUNT(*)`)).
		From(q.modelInfo.Table).
		Where(q.conditions...).
		Row()

	var count int

	err = row.Scan(&count)
	if err != nil {
		return 0, err
	}

	return count, nil
}

// First reads the first matching row into the struct that model points to,
// and loads the relations requested with With. Without conditions, it
// looks up the model by its current primary key values. It returns
// ErrNoRows if there is no match.
//
// Lookups by primary key are served from the cache when possible, and
// misses are cached too.
func (q *Query) First(model interface{}) error {
	t := reflect.TypeOf(model)
	if t.Kind() != reflect.Ptr {
		return ErrNotPointer
	}

	err := q.setModel(model)
	if err != nil {
		return err
	}

	if len(q.conditions) == 0 {
		q.conditions = q.primaryKeyConditions()
	}

	pk := q.primaryKeyFromConditions(q.conditions)
	if (len(pk) > 0) && (len(q.columns) == 0) {
		err = q.cacheGet(pk)
		if err == nil {
			return nil
		}
		if err == cache.ErrEmptyObject {
			return ErrNoRows
		}
	}

	db, err := q.modelDB()
	if err != nil {
		return err
	}

	fd := q.parseFields()

	row := db.Select(fd.columns...).
		From(q.modelInfo.Table).
		Where(q.conditions...).
		Order(q.order...).
		Limit(1).
		Row()

	q.clearModel()

	err = q.scan(row, fd)
	if err != nil {
		if err == ErrNoRows {
			q.cacheSetEmpty(pk)
		}
		return err
	}

	if len(q.columns) == 0 {
		q.cacheSet(pk)
	}

	err = q.loadRelated()
	if err != nil {
		return err
	}

	return nil
}

// Find reads all matching rows into the slice that models points to, which
// may hold structs or pointers to structs, and loads the relations
// requested with With for each of them.
func (q *Query) Find(models interface{}) error {
	t := reflect.TypeOf(models)
	if t.Kind() != reflect.Ptr {
		return ErrNotPointer
	}

	t = t.Elem()
	if t.Kind() != reflect.Slice {
		return ErrNotSlice
	}

	err := q.setModelByType(t.Elem())
	if err != nil {
		return err
	}

	rv := reflect.ValueOf(models).Elem()
	rv.Set(
		reflect.MakeSlice(t, 0, 0),
	)

	db, err := q.modelDB()
	if err != nil {
		return err
	}

	fd := q.parseFields()

	rows, err := db.Select(fd.columns...).
		From(q.modelInfo.Table).
		Where(q.conditions...).
		Order(q.order...).
		Limit(q.limit...).
		Rows()
	if err != nil {
		return err
	}
	defer rows.Close()

	for rows.Next() {
		q.clearModel()

		err := q.scan(rows, fd)
		if err != nil {
			return err
		}

		if len(q.columns) == 0 {
			q.cacheSet(q.modelPrimaryKey())
		}

		err = q.loadRelated()
		if err != nil {
			return err
		}

		newItem := q.newValue(q.modelInfo.Type)
		q.copyStruct(newItem.Elem(), q.modelValue)

		if t.Elem().Kind() != reflect.Ptr {
			newItem = newItem.Elem()
		}
		rv.Set(
			reflect.Append(rv, newItem),
		)
	}

	return nil
}

// LoadRelated loads the named relations of a model that has already been
// read. See With for the name syntax.
func (q *Query) LoadRelated(model interface{}, relations ...string) error {
	err := q.setModel(model)
	if err != nil {
		return err
	}

	q.With(relations...)

	err = q.loadRelated()
	if err != nil {
		return err
	}

	return nil
}

// Create inserts model. Auto-increment fields are not inserted, and are set
// from the generated value afterwards: with RETURNING on PostgreSQL and
// LastInsertId elsewhere. It returns ErrDuplicateKey on unique
// violations.
func (q *Query) Create(model interface{}) error {
	err := q.setModel(model)
	if err != nil {
		return err
	}

	data := query.Data{}
	var autoIncrement *FieldInfo

	for _, fi := range q.modelInfo.Fields {
		if fi.AutoIncrement {
			autoIncrement = fi
			continue
		}

		data[fi.Column] = q.value(fi)
	}

	db, err := q.modelDB()
	if err != nil {
		return err
	}

	if autoIncrement != nil {
		var id int64

		if db.Driver() == database.DriverPostgres {
			row := db.Insert(q.modelInfo.Table, data).
				Returning(autoIncrement.Column).
				Row()

			err := row.Scan(&id)
			if db.Helper().IsDuplicateKey(err) {
				return ErrDuplicateKey{err}
			}
			if err != nil {
				return err
			}
		} else {
			res, err := db.Insert(q.modelInfo.Table, data).
				Exec()
			if db.Helper().IsDuplicateKey(err) {
				return ErrDuplicateKey{err}
			}
			if err != nil {
				return err
			}

			id, err = res.LastInsertId()
			if err != nil {
				return err
			}
		}

		field := fieldByIndex(q.modelValue, autoIncrement.FieldIndex...)
		value := reflect.ValueOf(id).Convert(field.Type())
		field.Set(value)
	} else {
		_, err := db.Insert(q.modelInfo.Table, data).
			Exec()
		if db.Helper().IsDuplicateKey(err) {
			return ErrDuplicateKey{err}
		}
		if err != nil {
			return err
		}
	}

	q.cacheClear()

	return nil
}

// Save updates the row of model, found by its primary key. With columns,
// only those columns are updated; otherwise all fields except primary and
// skip fields are. A model without primary key values is inserted with
// Create instead. It returns ErrDuplicateKey on unique violations.
func (q *Query) Save(model interface{}, columns ...string) error {
	err := q.setModel(model)
	if err != nil {
		return err
	}

	conditions := q.primaryKeyConditions()
	if len(conditions) == 0 {
		return q.Create(model)
	}

	q.columns = columns

	data := make(query.Data)
	for _, fi := range q.modelInfo.Fields {
		if fi.Primary {
			continue
		}

		column := fi.Column
		if len(q.columns) > 0 {
			if q.columns.IndexOf(column) < 0 {
				continue
			}
		} else if fi.Skip {
			continue
		}

		data[column] = q.value(fi)
	}
	if len(data) == 0 {
		return nil
	}

	db, err := q.modelDB()
	if err != nil {
		return err
	}

	_, err = db.Update(q.modelInfo.Table, data).
		Where(conditions).
		Exec()
	if db.Helper().IsDuplicateKey(err) {
		return ErrDuplicateKey{err}
	}
	if err != nil {
		return err
	}

	q.cacheClear()

	return nil
}

// Delete deletes the row of model, found by its primary key, and removes it
// and its has-many lists from the cache. It returns ErrNoPrimaryKey if the
// key is not set.
func (q *Query) Delete(model interface{}) error {
	err := q.setModel(model)
	if err != nil {
		return err
	}

	conditions := q.primaryKeyConditions()
	if len(conditions) == 0 {
		return ErrNoPrimaryKey
	}

	db, err := q.modelDB()
	if err != nil {
		return err
	}

	_, err = db.Delete(q.modelInfo.Table).
		Where(conditions...).
		Exec()
	if err != nil {
		return err
	}

	q.hasManyCacheClear()
	q.cacheClear()

	return nil
}

// DeleteAll deletes all rows that match the conditions in the table of
// model. Without conditions it deletes every row. It does not update the
// cache.
func (q *Query) DeleteAll(model interface{}) error {
	err := q.setModel(model)
	if err != nil {
		return err
	}

	db, err := q.modelDB()
	if err != nil {
		return err
	}

	_, err = db.Delete(q.modelInfo.Table).
		Where(q.conditions...).
		Order(q.order...).
		Limit(q.limit...).
		Exec()
	if err != nil {
		return err
	}

	return nil
}

// DeleteFromCache removes model and its has-many lists from the cache, for
// use after the row was changed without the ORM.
func (q *Query) DeleteFromCache(model interface{}) error {
	err := q.setModel(model)
	if err != nil {
		return err
	}

	q.hasManyCacheClear()
	return q.cacheClear()
}

// setModel makes model the target of the query.
func (q *Query) setModel(model interface{}) error {
	q.model = model

	q.modelValue = reflect.ValueOf(q.model)
	for q.modelValue.Kind() == reflect.Ptr {
		q.modelValue = q.modelValue.Elem()
	}

	q.modelInfo = GetModelInfo(q.model)
	if q.modelInfo == nil {
		return ErrInvalidModel
	}

	return nil
}

// setModelByType makes a new value of modelType the target of the query.
func (q *Query) setModelByType(modelType reflect.Type) error {
	q.modelValue = q.newValue(modelType).Elem()

	q.model = q.modelValue.Interface()

	q.modelInfo = GetModelInfo(q.model)
	if q.modelInfo == nil {
		return ErrInvalidModel
	}

	return nil
}

// clearModel zeroes the target, so values from a previous row do not leak
// into the next one.
func (q *Query) clearModel() {
	for i := 0; i < q.modelValue.NumField(); i++ {
		f := q.modelValue.Field(i)
		if f.IsZero() {
			continue
		}

		f.Set(reflect.Zero(f.Type()))
	}
}

// modelDB returns the transaction set with Tx, or the model's connection.
func (q *Query) modelDB() (interfaces.DB, error) {
	if q.tx != nil {
		return q.tx, nil
	}

	db, err := database.Get(q.modelInfo.Database)
	if err != nil {
		return nil, err
	}

	return db, nil
}

// modelName returns the full name of the model type, used in cache keys.
func (q *Query) modelName() string {
	return q.modelNameByType(q.modelInfo.Type)
}

func (q *Query) modelNameByType(t reflect.Type) string {
	return t.PkgPath() + "." + t.Name()
}

// modelPrimaryKey returns the primary key values of the target, or nil if
// an auto-increment key is still zero.
func (q *Query) modelPrimaryKey() []interface{} {
	a := make([]interface{}, len(q.modelInfo.Primary))
	for i, fi := range q.modelInfo.Primary {
		v := fieldByIndex(q.modelValue, fi.FieldIndex...).Interface()
		if fi.AutoIncrement && !typeconv.Bool(v) {
			return nil
		}

		a[i] = v
	}

	return a
}

// parseFields returns the columns to read and the target fields to scan
// them into.
func (q *Query) parseFields() *fieldsData {
	n := len(q.modelInfo.Fields)

	fields := make([]reflect.Value, 0, n)
	columns := make([]interface{}, 0, n)
	values := make([]interface{}, 0, n)
	info := make([]*FieldInfo, 0, n)

	for _, fi := range q.modelInfo.Fields {
		if len(q.columns) > 0 {
			if q.columns.IndexOf(fi.Column) < 0 {
				continue
			}
		} else if fi.Skip {
			continue
		}

		columns = append(columns, fi.Column)

		f := fieldByIndex(q.modelValue, fi.FieldIndex...)
		fields = append(fields, f)

		v := f.Addr().Interface()
		values = append(values, v)

		info = append(info, fi)
	}

	return &fieldsData{
		fields,
		columns,
		values,
		info,
	}
}

// scan reads a row into the target fields, decoding base64 fields.
func (q *Query) scan(row interfaces.Row, fd *fieldsData) error {
	err := row.Scan(fd.values...)
	if err != nil {
		return err
	}

	for i, f := range fd.fields {
		rv := reflect.ValueOf(fd.values[i]).Elem()

		if fd.info[i].Base64 {
			q.decodeBase64(rv)
		}

		f.Set(rv)
	}

	return nil
}

// value returns the value to write for a field, encoding base64 fields.
func (q *Query) value(fi *FieldInfo) interface{} {
	f := fieldByIndex(q.modelValue, fi.FieldIndex...)
	v := f.Interface()

	if fi.Base64 {
		v = q.encodeBase64(f)
	}

	return v
}

// primaryKeyConditions returns conditions that match the target's primary
// key, or nil if it is not set.
func (q *Query) primaryKeyConditions() query.And {
	pk := q.modelPrimaryKey()
	if len(pk) == 0 {
		return nil
	}

	a := make(query.And, len(q.modelInfo.Primary))
	for i, fi := range q.modelInfo.Primary {
		a[i] = query.Eq{fi.Column: pk[i]}
	}

	return a
}

// primaryKeyFromConditions returns the primary key values if conditions
// are plain equality conditions on the primary key columns, so the lookup
// can use the cache. Otherwise it returns nil.
func (q *Query) primaryKeyFromConditions(conditions []interface{}) []interface{} {
	m := q.conditionsMap(conditions)
	if len(m) < len(q.modelInfo.Primary) {
		return nil
	}

	a := make([]interface{}, len(q.modelInfo.Primary))
	for i, fi := range q.modelInfo.Primary {
		v, ok := m[fi.Column]
		if !ok {
			return nil
		}
		a[i] = v
	}

	return a
}

// relationConditions returns conditions that select the related rows of
// the target.
func (q *Query) relationConditions(relation *Relation) query.And {
	a := make(query.And, len(relation.Key))
	for i, fi := range relation.Key {
		value := fieldByIndex(q.modelValue, relation.Reference[i].FieldIndex...).Interface()
		a[i] = query.Eq{
			fi.Column: value,
		}
	}

	return a
}

// conditionsMap collects the column values of Eq conditions, also inside
// And.
func (q *Query) conditionsMap(conditions []interface{}) map[string]interface{} {
	m := make(map[string]interface{})
	for _, cond := range conditions {
		switch t := cond.(type) {
		case query.And:
			tm := q.conditionsMap(t)
			for k, v := range tm {
				m[k] = v
			}
		case query.Eq:
			for k, v := range t {
				m[k] = v
			}
		}
	}

	return m
}

// cacheClear removes the target from the cache, together with the
// has-many lists of its belongs-to parents that may contain it.
func (q *Query) cacheClear() error {
	q.belongsToCacheClear()

	pk := q.modelPrimaryKey()

	err := q.cacheDelete(pk)
	if err != nil {
		return err
	}

	return nil
}

// cacheKey returns the cache key of a model: its type name, the model info
// checksum and the JSON primary key. The checksum changes when the model
// definition changes, so stale entries are not read after a deploy.
func (q *Query) cacheKey(pk []interface{}) string {
	if len(pk) == 0 {
		return ""
	}

	b, err := json.Marshal(pk)
	if err != nil {
		return ""
	}

	key := fmt.Sprintf("%s<%016x>%s", q.modelName(), q.modelInfo.Checksum, b)
	return key
}

// cacheGet reads the target from the cache and loads its relations.
func (q *Query) cacheGet(pk []interface{}) error {
	key := q.cacheKey(pk)
	if key == "" {
		return ErrNoPrimaryKey
	}

	err := cacheStorage.Get(key, q.model)
	if err != nil {
		return err
	}

	err = q.loadRelated()
	if err != nil {
		return err
	}

	return nil
}

// cacheSet stores the target in the cache.
func (q *Query) cacheSet(pk []interface{}) error {
	key := q.cacheKey(pk)
	if key == "" {
		return ErrNoPrimaryKey
	}

	err := cacheStorage.Set(key, q.modelValue.Interface(), cache.DefaultTTL)
	return err
}

// cacheSetEmpty records in the cache that there is no row for pk.
func (q *Query) cacheSetEmpty(pk []interface{}) error {
	key := q.cacheKey(pk)
	if key == "" {
		return ErrNoPrimaryKey
	}

	err := cacheStorage.Set(key, nil, cache.DefaultTTL)
	return err
}

// cacheDelete removes the cache entry for pk.
func (q *Query) cacheDelete(pk []interface{}) error {
	key := q.cacheKey(pk)
	if key == "" {
		return ErrNoPrimaryKey
	}

	err := cacheStorage.Delete(key)
	return err
}

// parseRelationName parses a With argument.
func (q *Query) parseRelationName(r string) queryRelation {
	m := relationNameRegexp.FindStringSubmatch(r)
	if m == nil {
		panic(fmt.Sprintf(`invalid relation name: "%s"`, r))
	}

	var with []string
	if m[3] != "" {
		with = strings.Split(m[3], ",")
		for i, w := range with {
			with[i] = strings.TrimSpace(w)
		}
	}

	return queryRelation{
		name: m[1],
		with: with,
	}
}

// loadRelated loads the relations requested with With into the target.
func (q *Query) loadRelated() error {
	if len(q.relations) == 0 {
		return nil
	}

	for _, relation := range q.relations {
		var err error

		if rel, ok := q.modelInfo.BelongsTo[relation.name]; ok {
			err = q.loadBelongsTo(rel, relation.with...)
		} else if rel, ok := q.modelInfo.HasMany[relation.name]; ok {
			err = q.loadHasMany(rel, relation.with...)
		} else {
			err = fmt.Errorf("unknown relation: %q", relation)
		}

		if err != nil {
			return err
		}
	}

	return nil
}

// relationFieldName returns the name of the relation's field.
func (q *Query) relationFieldName(relation *Relation) string {
	return q.modelInfo.Type.FieldByIndex(relation.FieldIndex).Name
}

// loadBelongsTo loads a belongs-to relation into the target.
func (q *Query) loadBelongsTo(relation *Relation, with ...string) error {
	field := q.modelValue.FieldByIndex(relation.FieldIndex)
	t := field.Type()
	v := q.newValue(t)
	conditions := q.relationConditions(relation)

	cached := q.belongsToCacheGet(relation, conditions)
	if cached != nil {
		v = *cached
	} else {
		err := Where(conditions...).First(v.Interface())
		if err != nil {
			return err
		}

		if t.Kind() != reflect.Ptr {
			v = v.Elem()
		}

		q.belongsToCacheSet(relation, conditions, v)
	}

	if len(with) > 0 {
		err := LoadRelated(v.Interface(), with...)
		if err != nil {
			return err
		}
	}

	field.Set(v)
	return nil
}

// belongsToCacheClear removes the cached has-many lists of the target's
// parents that include the target's table.
func (q *Query) belongsToCacheClear() {
	for _, relation := range q.modelInfo.BelongsTo {
		q.belongsToCacheClearRelation(relation)
	}
}

// belongsToCacheClearRelation removes the cached has-many lists of the
// parent in belongsTo that point back to the target's table.
func (q *Query) belongsToCacheClearRelation(belongsTo *Relation) {
	f := q.modelValue.FieldByIndex(belongsTo.FieldIndex)

	t := f.Type()
	for t.Kind() == reflect.Ptr {
		t = t.Elem()
	}

	v := reflect.New(t)
	mi := GetModelInfo(v.Interface())

	for _, hasMany := range mi.HasMany {
		if hasMany.Database != q.modelInfo.Database {
			continue
		}
		if hasMany.Table != q.modelInfo.Table {
			continue
		}

		for i, fi := range belongsTo.Key {
			k := fieldByIndex(q.modelValue, belongsTo.Reference[i].FieldIndex...)
			fieldByIndex(v.Elem(), fi.FieldIndex...).Set(k)
		}

		q := new(Query)
		err := q.setModel(v.Elem().Interface())
		if err != nil {
			continue
		}

		q.hasManyCacheClearRelation(hasMany)
	}
}

// belongsToCacheKey returns the key of a parent in belongsToCache.
func (q *Query) belongsToCacheKey(conditions query.And) string {
	m := q.conditionsMap(conditions)

	b, err := json.Marshal(m)
	if err != nil {
		return ""
	}

	key := string(b)
	return key
}

func (q *Query) belongsToCacheGet(relation *Relation, conditions query.And) *reflect.Value {
	cacheKey := q.belongsToCacheKey(conditions)
	if cacheKey == "" {
		return nil
	}

	fieldName := q.relationFieldName(relation)

	value, ok := q.belongsToCache[fieldName][cacheKey]
	if !ok {
		return nil
	}

	return &value
}

func (q *Query) belongsToCacheSet(relation *Relation, conditions query.And, value reflect.Value) {
	cacheKey := q.belongsToCacheKey(conditions)
	if cacheKey == "" {
		return
	}

	fieldName := q.relationFieldName(relation)

	if q.belongsToCache == nil {
		q.belongsToCache = map[string]map[string]reflect.Value{}
	}
	if _, ok := q.belongsToCache[fieldName]; !ok {
		q.belongsToCache[fieldName] = map[string]reflect.Value{}
	}

	q.belongsToCache[fieldName][cacheKey] = value
}

// loadHasMany loads a has-many relation into the target, from the cache if
// possible.
func (q *Query) loadHasMany(relation *Relation, with ...string) error {
	field := q.modelValue.FieldByIndex(relation.FieldIndex)
	t := field.Type()
	a := reflect.New(t)
	a.Elem().Set(
		reflect.MakeSlice(t, 0, 0),
	)
	models := a.Interface()
	conditions := q.relationConditions(relation)

	cached := false
	cacheKey := q.hasManyCacheKey(relation)
	if cacheKey != "" {
		err := cacheStorage.Get(cacheKey, models)
		if err == nil {
			cached = true
		}
	}

	if !cached {
		q := Where(conditions...).Order(relation.Order...).Limit(relation.Limit)
		if relation.Filter != nil {
			q.Where(relation.Filter)
		}

		err := q.Find(models)
		if err != nil {
			return err
		}

		cacheStorage.Set(cacheKey, models, cache.DefaultTTL)
	}

	if len(with) > 0 {
		n := a.Elem().Len()
		for i := 0; i < n; i++ {
			err := LoadRelated(a.Elem().Index(i).Interface(), with...)
			if err != nil {
				return err
			}
		}
	}

	field.Set(a.Elem())
	return nil
}

// hasManyCacheClear removes the target's cached has-many lists.
func (q *Query) hasManyCacheClear() {
	for _, relation := range q.modelInfo.HasMany {
		q.hasManyCacheClearRelation(relation)
	}
}

func (q *Query) hasManyCacheClearRelation(relation *Relation) {
	cacheKey := q.hasManyCacheKey(relation)
	if cacheKey == "" {
		return
	}

	cacheStorage.Delete(cacheKey)
}

// hasManyCacheKey returns the cache key of a has-many list: the model's
// cache key plus the field name.
func (q *Query) hasManyCacheKey(relation *Relation) string {
	pk := q.modelPrimaryKey()
	key := q.cacheKey(pk) + "." + q.modelInfo.Type.FieldByIndex(relation.FieldIndex).Name
	return key
}

// newValue returns a pointer to a new zero value of t, dereferencing
// pointer types first.
func (q *Query) newValue(t reflect.Type) reflect.Value {
	for t.Kind() == reflect.Ptr {
		t = t.Elem()
	}
	return reflect.New(t)
}

// copyStruct copies the settable fields of src into dst.
func (q *Query) copyStruct(dst reflect.Value, src reflect.Value) {
	n := dst.NumField()
	for i := 0; i < n; i++ {
		f := dst.Field(i)
		if f.CanSet() {
			f.Set(src.Field(i))
		}
	}
}

// encodeBase64 returns a []byte field as base64, or "" for other types.
func (q *Query) encodeBase64(rv reflect.Value) string {
	if !q.isSliceOfUint8(rv.Type()) {
		return ""
	}

	for rv.Kind() == reflect.Ptr {
		rv = rv.Elem()
	}

	s := base64.StdEncoding.EncodeToString(rv.Bytes())
	return s
}

// decodeBase64 decodes a []byte field read as base64 text in place. Invalid
// data is left as it is.
func (q *Query) decodeBase64(rv reflect.Value) {
	if !q.isSliceOfUint8(rv.Type()) {
		return
	}

	for rv.Kind() == reflect.Ptr {
		rv = rv.Elem()
	}

	b, err := base64.StdEncoding.DecodeString(string(rv.Bytes()))
	if err != nil {
		return
	}

	rv.SetBytes(b)
}

// isSliceOfUint8 reports whether t is []byte or a pointer to it.
func (q *Query) isSliceOfUint8(t reflect.Type) bool {
	for t.Kind() == reflect.Ptr {
		t = t.Elem()
	}
	return (t.Kind() == reflect.Slice) && (t.Elem().Kind() == reflect.Uint8)
}
